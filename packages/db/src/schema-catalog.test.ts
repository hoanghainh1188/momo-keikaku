// The I/O matrix. Two short-lived probe Tenants, removed before and after.

const TENANT_X = 'ten-catalog-x';
const TENANT_Y = 'ten-catalog-y';
const MATRIX_TENANTS = [TENANT_X, TENANT_Y];

async function setTenant(client: pg.Client, tenantId: string): Promise<void> {
  await client.query(`SELECT set_config('app.tenant_id', $1, true)`, [tenantId]);
}

/** A Tenant with one Department and one Project, inside the caller's transaction. */
async function writeTenantShell(client: pg.Client, tenantId: string): Promise<string> {
  const projectId = `${tenantId}-prj`;
  await client.query('INSERT INTO tenant (id, name) VALUES ($1, $1)', [tenantId]);
  await setTenant(client, tenantId);
  await client.query('INSERT INTO department (id, tenant_id, name) VALUES ($1, $2, $1)', [
    `${tenantId}-dep`,
    tenantId,
  ]);
  await client.query(
    `INSERT INTO project (id, tenant_id, department_id, name, client_name, contract_type,
       tz_offset_minutes, teirei_weekday, default_rate_jpy, eac_method, calendar_jp, calendar_vn,
       demo_anchor)
     VALUES ($1, $2, $3, $1, 'client', '請負', 540, 1, 0, 'typical', true, false,
       '2026-09-16T09:00:00Z')`,
    [projectId, tenantId, `${tenantId}-dep`],
  );
  return projectId;
}

/** Inserts one Work Package; `childCount > 0` makes it a summary. */
async function writeWp(
  client: pg.Client,
  tenantId: string,
  projectId: string,
  id: string,
  extra: {
    parentId?: string;
    childCount?: number;
    durationDays?: number;
    constraintType?: string;
    constraintDate?: string;
  } = {},
): Promise<void> {
  await client.query(
    `INSERT INTO work_package (id, tenant_id, project_id, wbs_code, name, parent_id, child_count,
       is_milestone, is_catch_all, duration_days, constraint_type, constraint_date, planned_mh,
       assigned_resource_ids)
     VALUES ($1, $2, $3, $1, $1, $4, $5, false, false, $6, $7, $8, 0, '{}')`,
    [
      id,
      tenantId,
      projectId,
      extra.parentId ?? null,
      extra.childCount ?? 0,
      extra.durationDays ?? null,
      extra.constraintType ?? 'asap',
      extra.constraintDate ?? null,
    ],
  );
}

/** Removes both matrix Tenants' rows, children first. Idempotent. */
async function removeMatrixTenants(client: pg.Client): Promise<void> {
  for (const tenantId of MATRIX_TENANTS) {
    await client.query('BEGIN');
    try {
      await setTenant(client, tenantId);
      for (const table of ['wp_dependency', 'work_package', 'project', 'department']) {
        await client.query(`DELETE FROM ${table} WHERE tenant_id = $1`, [tenantId]);
      }
      await client.query('DELETE FROM tenant WHERE id = $1', [tenantId]);
      await client.query('COMMIT');
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    }
  }
}

/** Runs `work` in a transaction that is always rolled back, returning its refusal code. */
async function refusedInRolledBackTx(
  work: (client: pg.Client) => Promise<unknown>,
): Promise<string | undefined> {
  return asOwner(async (client) => {
    await client.query('BEGIN');
    try {
      return await refusalCode(work(client));
    } finally {
      await client.query('ROLLBACK');
    }
  });
}

describe.skipIf(!reachable)('the I/O matrix of story 2.1, against the migrated schema', () => {
  beforeAll(async () => {
    await asOwner(removeMatrixTenants);
  });

  it('rejects a Work Package whose (tenant_id, project_id) names another Tenant\'s Project (23503)', async () => {
    const code = await refusedInRolledBackTx(async (client) => {
      const projectOfX = await writeTenantShell(client, TENANT_X);
      await writeTenantShell(client, TENANT_Y);
      await setTenant(client, TENANT_Y);
      await writeWp(client, TENANT_Y, projectOfX, 'wp-catalog-cross');
    });
    expect(code).toBe('23503');
  });

  it('rejects a dependency on a summary Work Package at COMMIT, not at the statement (23503)', async () => {
    const outcome = await asOwner(async (client) => {
      await client.query('BEGIN');
      try {
        const projectId = await writeTenantShell(client, TENANT_X);
        await writeWp(client, TENANT_X, projectId, 'wp-cat-summary', { childCount: 1 });
        await writeWp(client, TENANT_X, projectId, 'wp-cat-child', { parentId: 'wp-cat-summary' });
        await writeWp(client, TENANT_X, projectId, 'wp-cat-leaf');
        // Accepted here: the leaf FKs are DEFERRABLE INITIALLY DEFERRED.
        await client.query(
          `INSERT INTO wp_dependency (tenant_id, project_id, predecessor_wp_id, successor_wp_id)
           VALUES ($1, $2, 'wp-cat-summary', 'wp-cat-leaf')`,
          [TENANT_X, projectId],
        );
      } catch (error) {
        await client.query('ROLLBACK');
        return { statement: (error as { code?: string }).code ?? 'unknown', commit: undefined };
      }
      return { statement: undefined, commit: await refusalCode(client.query('COMMIT')) };
    });
    expect(outcome.statement, 'the insert itself was refused — the FK is not deferred').toBeUndefined();
    expect(outcome.commit).toBe('23503');
    // Nothing of the transaction landed.
    await asOwner(removeMatrixTenants);
  });

  it('commits an edge added before its endpoint\'s child_count is fixed in the same transaction', async () => {
    const code = await asOwner(async (client) => {
      await client.query('BEGIN');
      const projectId = await writeTenantShell(client, TENANT_X);
      // `wp-cat-a` starts as a summary (child_count 1) with no child yet — the middle of a re-parent.
      await writeWp(client, TENANT_X, projectId, 'wp-cat-a', { childCount: 1 });
      await writeWp(client, TENANT_X, projectId, 'wp-cat-b');
      await client.query(
        `INSERT INTO wp_dependency (tenant_id, project_id, predecessor_wp_id, successor_wp_id)
         VALUES ($1, $2, 'wp-cat-a', 'wp-cat-b')`,
        [TENANT_X, projectId],
      );
      await client.query(`UPDATE work_package SET child_count = 0 WHERE id = 'wp-cat-a'`);
      return refusalCode(client.query('COMMIT'));
    });
    await asOwner(removeMatrixTenants);
    expect(code, 'the re-parent was judged before COMMIT').toBeUndefined();
  });

  it('rejects a summary Work Package that carries a duration (23514)', async () => {
    const code = await refusedInRolledBackTx(async (client) => {
      const projectId = await writeTenantShell(client, TENANT_X);
      await writeWp(client, TENANT_X, projectId, 'wp-cat-dur', { childCount: 1, durationDays: 3 });
    });
    expect(code).toBe('23514');
  });

  it('rejects a summary Work Package that carries a constraint (23514)', async () => {
    const code = await refusedInRolledBackTx(async (client) => {
      const projectId = await writeTenantShell(client, TENANT_X);
      await writeWp(client, TENANT_X, projectId, 'wp-cat-cons', {
        childCount: 1,
        constraintType: 'must_finish_on',
        constraintDate: '2027-03-18',
      });
    });
    expect(code).toBe('23514');
  });

  it('rejects a summary Work Package that carries a constraint date under asap (23514)', async () => {
    const code = await refusedInRolledBackTx(async (client) => {
      const projectId = await writeTenantShell(client, TENANT_X);
      await writeWp(client, TENANT_X, projectId, 'wp-cat-cdate', {
        childCount: 1,
        constraintType: 'asap',
        constraintDate: '2027-03-18',
      });
    });
    expect(code).toBe('23514');
  });

  it('rejects a dependency type other than FS (23514)', async () => {
    const code = await refusedInRolledBackTx(async (client) => {
      const projectId = await writeTenantShell(client, TENANT_X);
      await writeWp(client, TENANT_X, projectId, 'wp-cat-p');
      await writeWp(client, TENANT_X, projectId, 'wp-cat-s');
      await client.query(
        `INSERT INTO wp_dependency (tenant_id, project_id, predecessor_wp_id, successor_wp_id, type)
         VALUES ($1, $2, 'wp-cat-p', 'wp-cat-s', 'SS')`,
        [TENANT_X, projectId],
      );
    });
    expect(code).toBe('23514');
  });
});

